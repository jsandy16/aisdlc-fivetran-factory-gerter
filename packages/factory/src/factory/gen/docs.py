"""Generated docs per pipeline (ADR-0018: regenerated wholesale, deterministic, so only changed pages differ).

runbook.md  how to start, rerun and diagnose a run; what runs where; what each failure class means and who hears.
lineage.md  where data comes from and goes: sources → rules (grouped by task) → artifacts → destination slots.
alerts.md   alert routing: failure class → exit code → Airflow behaviour → channel; the SLA.
Content comes from the spec, the planner and resource names only: ids, names and secret *names*, never values.
"""

from __future__ import annotations

from typing import Any

from factory_spec.catalog import Pricing
from factory_spec.derive import derive_artifacts
from factory_spec.spec import PipelineSpec

from ..plan.engine import plan
from . import names
from .names import Deploy

CLASSES = [  # (class, exit code, Airflow behaviour, first action)
    ("transient", 75, "retried with backoff; alerts after the last attempt",
     "check the dependency named in the log (portal, SFTP, S3, Fivetran); rerun with the same run key"),
    ("data", 65, "fails at once (not retried)",
     "read the rule id and code in the log; fix the source data or the portal answer; rerun"),
    ("config", 78, "fails at once (not retried)", "fix the binding, platform setting or secret reference; rebuild"),
    ("security", 77, "fails at once (not retried); nothing is delivered",
     "do not rerun; hand the audit events for the run to the security channel"),
    ("internal", 70, "fails at once (not retried)", "a framework defect: raise it with the platform team"),
]  # fmt: skip


def _table(header: list[str], rows: list[list[str]]) -> list[str]:
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(c.replace("|", "\\|") for c in r) + " |" for r in rows]
    return out


def _engine(task: Any, decisions: dict[str, Any]) -> str:
    return str(decisions[task.task_id]["choice"] if task.engine == "auto" else task.engine)


def runbook(spec: PipelineSpec, deploys: dict[str, Deploy], prices: Pricing | None = None) -> str:
    p, md = spec.pipeline, spec.pipeline.metadata
    pid, team = spec.pipeline_id, md.team
    decisions = {d["task_id"]: d for d in plan(spec, prices)["engine_decisions"]}
    alerts = p.observability.alerts
    trig = p.trigger
    out = [f"# Runbook: {md.name} (`{pid}`)", "", "Generated by `factory build`; do not edit.", ""]
    out += _table(["", ""], [
        ["DAG", f"`{names.dag_id(pid, md.spec_version)}` (spec {md.spec_version})"],
        ["Team", f"`{team}`; data engineer {md.owners.data_engineer}; platform {md.owners.platform}"],
        ["Trigger", f"`{trig.type}`"],
        ["Run key", f"`{p.reliability.run_key}` (one run per key; replay window {p.reliability.replay_window} s)"],
        ["Environments", ", ".join(f"`{e}`" for e in deploys) or "none bound"],
    ])  # fmt: skip
    out += ["", "## Starting and rerunning", ""]
    if trig.type in ("sqs", "s3_event"):
        out.append(f"- A message on queue `{trig.queue}` starts a run through the dispatcher Lambda "
                   f"`{names.dispatcher_function(team, pid)}`; after {trig.max_receive_count} failed deliveries the "
                   "message goes to the dead-letter queue, and an invalid one is quarantined under `_quarantine/` in "
                   "the staging bucket.")  # fmt: skip
    elif trig.type == "schedule":
        out.append(f"- Runs on the schedule `{trig.cron}` (UTC) unless an environment overrides it.")
    else:
        out.append("- Started by a person: trigger the DAG with a JSON conf holding `run_key` and the run parameters.")
    out += [
        "- **Rerun** a failed run by triggering the DAG again with the same `run_key` in the conf: completed tasks and"
        " rules are skipped, delivered files are never written twice, and the run uses the bundle it was pinned to.",
        "- A new run key is a new run. Never edit run-state records by hand.",
        "",
        "## Tasks",
        "",
    ]
    rows = []
    for t in p.orchestration.tasks:
        engine = _engine(t, decisions)
        where = f"Lambda `{names.lambda_function(team, pid, t.task_id)}`"
        if engine.startswith("eks_pod"):
            where = f"pod, service account `{names.service_account(pid, t.task_id)}` in `{names.namespace(team)}`"
        r = t.retry or p.reliability.retry
        rows.append([f"`{t.task_id}`", engine, where, f"{t.timeout} s", str(r.max_attempts),
                     ", ".join(f"`{x}`" for x in t.rules)])  # fmt: skip
    out += _table(["Task", "Engine", "Runs as", "Timeout", "Attempts", "Rules"], rows)
    out += ["", "## When a task fails", ""]
    out += _table(["Class", "Exit", "Airflow", "Alerted", "First action"],
                  [[c, str(code), how, f"`{getattr(alerts, c, 'platform')}`", act]
                   for c, code, how, act in CLASSES])  # fmt: skip
    out += ["", "## Evidence per environment", ""]
    out += _table(["Env", "Staging bucket", "Run state", "Audit store"],
                  [[f"`{e}`", f"`{d.staging_bucket}`", f"`{d.run_state_table}`", f"`{d.audit_store}`"]
                   for e, d in deploys.items()])  # fmt: skip
    refs = sorted(spec.integrations.secrets)
    if refs:
        out += ["", f"Secrets used (names only; values are resolved at run time): {', '.join(f'`{s}`' for s in refs)}."]
    return "\n".join(out) + "\n"


def lineage(spec: PipelineSpec) -> str:
    graph = derive_artifacts(spec).artifacts
    task_of = {r: t.task_id for t in spec.pipeline.orchestration.tasks for r in t.rules}
    out = [f"# Lineage: `{spec.pipeline_id}`", "", "Generated by `factory build`; do not edit.", "", "```mermaid",
           "flowchart LR", f"  trigger([trigger: {spec.pipeline.trigger.type}])"]  # fmt: skip
    for t in spec.pipeline.orchestration.tasks:
        out.append(f"  subgraph {t.task_id}[task {t.task_id}]")
        out += [f"    {r}[{r}]" for r in t.rules]
        out.append("  end")
    edges: list[str] = []
    ends: set[str] = set()
    for rule in spec.rules.rules:
        params = getattr(rule.implementation, "params", None)
        par = params.model_dump(mode="json") if params is not None and hasattr(params, "model_dump") else {}
        if isinstance(par.get("source"), str):
            ends.add(f"  src_{par['source']}[(source {par['source']})]")
            edges.append(f"  src_{par['source']} --> {rule.rule_id}")
        if isinstance(par.get("slot"), str):
            ends.add(f"  slot_{par['slot']}[/destination {par['slot']}/]")
            edges.append(f"  {rule.rule_id} --> slot_{par['slot']}")
        if not rule.inputs and not isinstance(par.get("source"), str):
            edges.append(f"  trigger --> {rule.rule_id}")
        for name in rule.inputs:
            a = graph.get(name)
            edges.append(f"  {a.rule_id if a else 'trigger'} -- {name} --> {rule.rule_id}")
    out += sorted(ends) + edges + ["```", "", "## Artifacts", ""]
    out += _table(["Artifact", "Kind", "Produced by", "Task", "Kept as", "Read by"],
                  [[f"`{n}`", a.kind, f"`{a.rule_id}`", f"`{task_of.get(a.rule_id, a.task_id)}`", a.durability,
                    ", ".join(f"`{r}`" for r, _ in sorted(a.consumers)) or "-"]
                   for n, a in sorted(graph.items())])  # fmt: skip
    dests = spec.destinations.destinations
    if dests:
        out += ["", "## Destination allow-list (governance)", ""]
        out += _table(["Env", "Id", "Type", "Slots"], [[f"`{env}`", f"`{e.id}`", e.type, ", ".join(e.slots)]
                                                      for env, es in sorted(dests.items()) for e in es])  # fmt: skip
    return "\n".join(out) + "\n"


def alerts(spec: PipelineSpec) -> str:
    obs = spec.pipeline.observability
    out = [f"# Alert routing: `{spec.pipeline_id}`", "", "Generated by `factory build`; do not edit.", "",
           "Channel ids are resolved by the platform (alarms and topics are wired in Phase 8). `none` means the "
           "failure is visible in Airflow only.", ""]  # fmt: skip
    out += _table(
        ["Failure class", "Exit code", "Airflow", "Channel"],
        [[c, str(code), how, f"`{getattr(obs.alerts, c, 'platform')}`"] for c, code, how, _ in CLASSES],
    )
    out.append("")
    if obs.sla:
        out.append(f"- A run takes longer than the SLA ({obs.sla} s): `{obs.alerts.data}`.")
    if spec.pipeline.trigger.type in ("sqs", "s3_event"):
        out.append("- The dead-letter queue is not empty: `platform`.")
    return "\n".join(out) + "\n"


def pipeline_docs(spec: PipelineSpec, deploys: dict[str, Deploy], prices: Pricing | None = None) -> dict[str, str]:
    return {"runbook.md": runbook(spec, deploys, prices), "lineage.md": lineage(spec), "alerts.md": alerts(spec)}
