"""`factory verify`: regenerate in memory and compare with the committed build (ADR-0017 proof).

Each finding says what went wrong, so the fix is obvious:
  generated_file_edited      the file no longer matches its own BUILD-MANIFEST hash: someone edited generated output
  build_stale                the build was consistent but the spec, lock, prices or framework changed: rebuild
  generated_file_missing     a file the build recorded is absent (deleted)
  generated_file_unexpected  a file the factory never generated sits in the build folder
  build_missing              no build at all
The spec side (valid spec, current lock, accepted custom rules) is checked by the same render that `factory build` runs.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from factory_spec.repo import Repo

from .build import MANIFEST, render


def _sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def verify(repo: Repo, pipeline_dir: Path, out_root: Path) -> dict[str, Any]:
    if repo.config.layout == "dataops":
        from .dataops.layout import verify_dataops

        return verify_dataops(repo, pipeline_dir)
    out = out_root / pipeline_dir.name
    issues: list[dict[str, str]] = []

    def add(code: str, file: str, msg: str) -> None:
        issues.append({"code": code, "file": file, "msg": msg})

    on_disk: dict[str, Any] = {}
    if (out / MANIFEST).is_file():
        try:
            on_disk = json.loads((out / MANIFEST).read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            add("generated_file_edited", MANIFEST, "the manifest is not valid JSON")
    elif out.is_dir():
        add("generated_file_missing", MANIFEST, "the build has no manifest")
    else:
        add("build_missing", str(out), "no build: run `factory build`")
        return {"ok": False, "issues": issues, "checked": 0}
    recorded: dict[str, str] = on_disk.get("files", {}) if isinstance(on_disk.get("files"), dict) else {}
    image = on_disk.get("image") if isinstance(on_disk.get("image"), str) else None
    fresh = render(repo, pipeline_dir, image=image)
    for rel, data in fresh.files.items():
        f = out / rel
        if not f.is_file():
            if rel in recorded or not recorded:
                add("generated_file_missing", rel, "deleted from the build: rebuild")
            else:
                add("build_stale", rel, "new output of the changed spec: rebuild")
            continue
        have = _sha(f.read_bytes())
        if have == _sha(data):
            continue
        if rel in recorded and have != recorded[rel]:
            add("generated_file_edited", rel, "edited after the build; change the spec and rebuild instead")
        else:
            add("build_stale", rel, "out of date with the spec: rebuild")
    present = sorted(p.relative_to(out).as_posix() for p in out.rglob("*") if p.is_file())
    for rel in present:
        if rel == MANIFEST or rel in fresh.files:
            continue
        if rel in recorded:
            add("build_stale", rel, "no longer generated from the spec: rebuild")
        else:
            add("generated_file_unexpected", rel, "not generated by the factory")
    if not issues and (out / MANIFEST).read_bytes() != fresh.manifest_bytes:
        add("build_stale", MANIFEST, "the manifest is out of date: rebuild")
    return {"ok": not issues, "issues": issues, "checked": len(fresh.files) + 1,
            "manifest_sha256": _sha(fresh.manifest_bytes)}  # fmt: skip
