"""The generated src/<pipeline>/task.py (ADR-0026): the Airflow task of a DataOps DAG, as readable Python.

It follows the team repository's conventions (AGENTS.md): logging instead of print, `main()` as the entry point, one
named function per step with the step's plain-English description as its docstring, one function per task. Each step
calls the framework library (src/shared/factory), which runs the rule with retries, idempotency and audit. The file is
generated: a hand edit is reported by `factory verify`, and the library refuses steps out of the spec's order.
"""

from __future__ import annotations

import keyword
import textwrap
from typing import Any

from factory_spec.spec import PipelineSpec

RESERVED = frozenset({"main", "run_pipeline", "log", "logging", "os", "sys", "Path", "Pipeline", "Run", "Task",
                      "PIPELINE_DIR", "FACTORY_LIB", "BUNDLE_SHA256", "ENV_VAR"})  # fmt: skip
WIDTH = 100


def _clean(text: str) -> str:
    """Plain text that is safe inside a docstring (no backslashes, no closing quotes)."""
    return " ".join(text.replace("\\", "/").replace('"""', "'''").split()).rstrip('"') or "No description."


def _doc(text: str, indent: str) -> list[str]:
    """A docstring, wrapped to the line length."""
    lines = textwrap.wrap(_clean(text), WIDTH - len(indent) - 6, break_on_hyphens=False)
    if len(lines) == 1:
        return [f'{indent}"""{lines[0]}"""']
    return [f'{indent}"""{lines[0]}', *[f"{indent}{x}" for x in lines[1:]], f'{indent}"""']


def step_names(spec: PipelineSpec) -> dict[str, str]:
    """rule id → function name: the id without its r_ prefix when that stays a unique, valid name."""
    taken = {t.task_id for t in spec.pipeline.orchestration.tasks} | RESERVED
    out: dict[str, str] = {}
    for _, rule in spec.ordered_rules():
        rid = str(rule.rule_id)
        short = rid.removeprefix("r_")
        name = short if short.isidentifier() and not keyword.iskeyword(short) and short not in taken else rid
        if name in taken or name in out.values():
            name = f"step_{rid}"
        out[rid] = name
    return out


def _trigger_line(spec: PipelineSpec, schedule: str) -> str:
    trig: Any = spec.pipeline.trigger
    if trig.type == "s3_event":
        return f"Trigger: S3 object-created events on queue '{trig.queue}', polled by every DAG run ({schedule})."
    if trig.type == "sqs":
        return f"Trigger: messages on queue '{trig.queue}', polled by every DAG run ({schedule})."
    if trig.type == "schedule":
        return f"Trigger: the DAG schedule ({schedule}); each run covers the minute it starts in."
    return "Trigger: started by a person; the run conf (with run_key) comes from FACTORY_RUN_CONF."


def generate_task_py(spec: PipelineSpec, bundle_sha256: str, env_var: str, schedule: str) -> str:
    pid = spec.pipeline_id
    md = spec.pipeline.metadata
    names = step_names(spec)
    head = textwrap.wrap(_clean(f"{md.name}: {md.description}"), WIDTH - 3, break_on_hyphens=False)
    out = ['"""' + head[0], *head[1:]]
    out += [
        "",
        f"Generated by Pipeline Factory from pipelines/{pid}/spec (spec {md.spec_version}). Do not edit this file:",
        f"change the spec, then run `factory lock {pid}` and `factory build {pid}`.",
        "",
        *textwrap.wrap(_clean(_trigger_line(spec, schedule)), WIDTH, break_on_hyphens=False),
        '"""',
        "",
        "import logging",
        "import os",
        "import sys",
        "from pathlib import Path",
        "",
        "PIPELINE_DIR = Path(__file__).resolve().parent",
        'FACTORY_LIB = PIPELINE_DIR.parent / "shared" / "factory"',
        "if str(FACTORY_LIB) not in sys.path:",
        "    sys.path.insert(0, str(FACTORY_LIB))",
        "",
        "from factory_runtime.container import Pipeline, Run, Task  # noqa: E402",
        "",
        f'BUNDLE_SHA256 = "{bundle_sha256}"',
        f'ENV_VAR = "{env_var}"',
        "",
        "logging.basicConfig(",
        '    level=logging.getLevelNamesMapping().get(os.environ.get("LOG_LEVEL", "INFO"), logging.INFO),',
        '    format="%(asctime)s | %(levelname)s | %(name)s | %(message)s",',
        ")",
        "log = logging.getLogger(__name__)",
    ]
    for _, rule in spec.ordered_rules():
        out += ["", "", f"def {names[rule.rule_id]}(task: Task) -> None:"]
        out += _doc(rule.plain_english, "    ")
        out.append(f'    task.step("{rule.rule_id}")')
    ordered_tasks: list[Any] = []
    for t, _ in spec.ordered_rules():
        if t not in ordered_tasks:
            ordered_tasks.append(t)
    for t in ordered_tasks:
        out += ["", "", f"def {t.task_id}(run: Run) -> None:"]
        label = t.label.strip() or f"Task {t.task_id}"
        out += _doc(label if label.endswith((".", "!", "?")) else label + ".", "    ")
        out.append(f'    with run.task("{t.task_id}") as task:')
        out += [f"        {names[r]}(task)" for r in t.rules]
    out += ["", "", "def run_pipeline(run: Run) -> None:", '    """One run of the pipeline: its tasks, in order."""']
    out += [f"    {t.task_id}(run)" for t in ordered_tasks]
    out += [
        "",
        "",
        "def main() -> int:",
        f'    log.info("Starting pipeline {pid}")',
        "    pipeline = Pipeline.load(PIPELINE_DIR, BUNDLE_SHA256, env_var=ENV_VAR)",
        "    exit_code = pipeline.run_each(run_pipeline)",
        f'    log.info("Pipeline {pid} finished with exit code %s", exit_code)',
        "    return exit_code",
        "",
        "",
        'if __name__ == "__main__":',
        "    sys.exit(main())",
    ]
    return "\n".join(out) + "\n"
