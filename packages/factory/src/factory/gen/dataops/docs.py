"""docs/pipelines/<pipeline>.md and docs/config-schemas/<pipeline>.schema.json for the dataops layout.

Written in the team repository's style (trigger, data flow, config keys, secrets, running locally, tests). Content
comes from the spec only: names and secret *names*, never values.
"""

from __future__ import annotations

from typing import Any

from factory_spec.spec import PipelineSpec

from .task_py import step_names


def _trigger(spec: PipelineSpec, schedule: str) -> str:
    trig: Any = spec.pipeline.trigger
    if trig.type == "s3_event":
        where = f" under `{trig.key_prefix}`" if trig.key_prefix else ""
        return (f"S3 `ObjectCreated` events{where} arrive on the queue `{trig.queue}` (its name per environment is "
                f"in `environments.yaml`). The DAG polls the queue on every run (`{schedule}`); each event is one run. "
                "A message is deleted once its run finished; a failed run leaves it for redelivery, and the "
                "queue's dead-letter queue catches messages that keep failing. Unreadable messages are "
                "quarantined.")  # fmt: skip
    if trig.type == "sqs":
        return (f"Messages on the queue `{trig.queue}`, polled on every DAG run (`{schedule}`); each message is one "
                "run. Failed runs leave their message for redelivery.")  # fmt: skip
    if trig.type == "schedule":
        return f"The DAG schedule `{schedule}` (UTC). Each run covers the minute it starts in."
    return ("Started by a person (`schedule: none`). The run parameters, with `run_key`, are passed as JSON in the "
            "`FACTORY_RUN_CONF` environment variable of the task.")  # fmt: skip


def pipeline_doc(spec: PipelineSpec, envs: list[str], env_var: str, schedule: str, dag: str) -> str:
    pid, md = spec.pipeline_id, spec.pipeline.metadata
    names = step_names(spec)
    out = [f"# {md.name}", "", md.description, "",
           f"Generated by `factory build` from `pipelines/{pid}/spec` (spec {md.spec_version}); do not edit.", "",
           "## Trigger", "", _trigger(spec, schedule), "", "## Data flow", ""]  # fmt: skip
    current = None
    for n, (task, rule) in enumerate(spec.ordered_rules(), 1):
        if task.task_id != current:
            current = task.task_id
            out.append(f"Task `{task.task_id}`{': ' + task.label if task.label else ''}")
            out.append("")
        out.append(f"{n}. `{names[rule.rule_id]}` ({rule.rule_id}): {' '.join(rule.plain_english.split())}")
    out += ["", f"DAG `{dag}` (`dags/{dag}.json`), entry point `src/{pid}/task.py`.", "", "## Config keys", "",
            f"`src/{pid}/config_<env>.json`, chosen by `{env_var}`: "
            + (", ".join(f"`{e}`" for e in envs) or "no environment bound") + ".", "",
            "| Key | Description |", "|---|---|",
            "| `runtime.region` | AWS region the pipeline runs in |",
            "| `runtime.staging_bucket` | Run state, staging, audit and bundles, under `runtime.store_prefix` |",
            "| `runtime.placement_accounts` | AWS account per placement alias |",
            "| `runtime.dataops_vault_*` | Where Vault secrets are read (no secret values) |",
            "| `runtime.allowed_env` | Proxy and CA variables the image sets, accepted as they are |",
            "| `poll.queue_url` | Queue polled by each DAG run (queue-triggered pipelines) |", ""]  # fmt: skip
    secrets = sorted(spec.integrations.secrets)
    out += ["## Secrets", ""]
    if secrets:
        out += ["Read at run time from the store each environment names (`environments.yaml` → `secrets`); "
                "only names appear here.", "", "| Secret | Kind | Path | Key |", "|---|---|---|---|"]  # fmt: skip
        for name in secrets:
            s = spec.integrations.secrets[name]
            out.append(f"| `{name}` | {s.kind} | `{s.path}` | {('`' + s.key + '`') if s.key else '-'} |")
    else:
        out.append("None.")
    out += ["", "## Running locally", "", "```bash",
            f"{env_var}=dev PYTHONPATH=src uv run python src/{pid}/task.py", "```", "",
            "It uses your AWS credentials and the `dev` bindings. Set `FACTORY_WORKDIR` to a scratch folder.", "",
            "## Tests", "", "```bash", f"PYTHONPATH=src uv run pytest tests/{pid}/ -v", "```", ""]  # fmt: skip
    return "\n".join(out)


def config_schema(pipeline_id: str) -> dict[str, Any]:
    s = {"type": "string"}
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": f"{pipeline_id} config_<env>.json",
        "type": "object",
        "required": ["environment", "runtime"],
        "additionalProperties": False,
        "properties": {
            "environment": s,
            "runtime": {
                "type": "object",
                "required": [
                    "team",
                    "pipeline_id",
                    "region",
                    "staging_bucket",
                    "audit_store",
                    "bundle_store",
                    "state_store",
                ],
                "properties": {
                    "team": s,
                    "pipeline_id": {"const": pipeline_id},
                    "region": s,
                    "staging_bucket": s,
                    "audit_store": s,
                    "bundle_store": s,
                    "state_store": {"const": "s3"},
                    "store_prefix": s,
                    "dag_id": s,
                    "image_digest": s,
                    "trusted_ca_file": s,
                    "project_entity": s,
                    "placement_accounts": {
                        "type": "object",
                        "additionalProperties": {"type": "string", "pattern": "^[0-9]{12}$"},
                    },
                    "allowed_env": {"type": "object", "additionalProperties": s},
                    "dataops_vault_address": s,
                    "dataops_vault_service_env": s,
                    "dataops_vault_token_secret": s,
                    "dataops_vault_token_region": s,
                    "dataops_vault_kv_path": s,
                },
            },
            "poll": {
                "type": "object",
                "required": ["queue_url"],
                "properties": {
                    "queue_url": s,
                    "max_messages": {"type": "integer"},
                    "wait_seconds": {"type": "integer"},
                    "max_runs": {"type": "integer"},
                },
            },
        },
    }
