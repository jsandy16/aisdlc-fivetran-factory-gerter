"""The generated tests/<pipeline>/test_task.py: checks the team's CI runs on every generated pipeline.

- the bundle next to task.py is the one task.py pins (sha256);
- every environment's config_<env>.json is a valid runtime configuration;
- task.py runs exactly the spec's steps, in the spec's order (read from the bundle, not from task.py);
- queue-triggered pipelines: one run against an empty queue in moto is a clean no-op (skipped without moto).
No AWS account and no data are needed; the smoke test uses synthetic credentials inside moto.
"""

from __future__ import annotations

from factory_spec.spec import PipelineSpec

STRICT = frozenset({"ppt", "prod", "prd"})


def generate_test_py(spec: PipelineSpec, envs: list[str], env_var: str) -> str:
    pid = spec.pipeline_id
    queue = spec.pipeline.trigger.type in ("sqs", "s3_event")
    smoke_env = next((e for e in envs if e not in STRICT), None)
    lines = [
        f'"""Tests for src/{pid}/task.py. Generated by Pipeline Factory; do not edit."""',
        "",
        "import hashlib",
        "import importlib.util",
        "import json",
        "from pathlib import Path",
        "",
        "import pytest",
        "",
        f'PIPELINE_DIR = Path(__file__).resolve().parents[2] / "src" / "{pid}"',
        f"ENVIRONMENTS = {envs!r}".replace("'", '"'),
        "",
        "",
        "def _task_module():",
        f'    spec = importlib.util.spec_from_file_location("{pid}_task", PIPELINE_DIR / "task.py")',
        "    module = importlib.util.module_from_spec(spec)",
        "    spec.loader.exec_module(module)",
        "    return module",
        "",
        "",
        "class _Recorder:",
        '    """Stands in for run.task(...) and task.step(...): records what task.py asks for."""',
        "",
        "    def __init__(self):",
        "        self.calls = []",
        "",
        "    def task(self, task_id):",
        '        self.calls.append(("task", task_id))',
        "        return self",
        "",
        "    def __enter__(self):",
        "        return self",
        "",
        "    def __exit__(self, *exc):",
        "        return False",
        "",
        "    def step(self, rule_id):",
        '        self.calls.append(("step", rule_id))',
        "",
        "",
        "def test_bundle_is_the_one_task_py_pins():",
        "    task = _task_module()",
        '    bundle = (PIPELINE_DIR / "pipeline_bundle.zip").read_bytes()',
        "    assert hashlib.sha256(bundle).hexdigest() == task.BUNDLE_SHA256",
        "",
        "",
        '@pytest.mark.parametrize("env", ENVIRONMENTS)',
        "def test_every_environment_has_a_runtime_configuration(env):",
        "    task = _task_module()",
        "    from factory_runtime.container import load_settings",
        "",
        "    cfg, _ = load_settings(PIPELINE_DIR, task.ENV_VAR, {task.ENV_VAR: env})",
        f'    assert (cfg.pipeline_id, cfg.env) == ("{pid}", env)',
        "",
        "",
        "def test_steps_run_in_the_order_of_the_spec(tmp_path):",
        "    task = _task_module()",
        "    from factory_spec.bundle import extract_bundle",
        "    from factory_spec.load import load_spec",
        "",
        '    extract_bundle((PIPELINE_DIR / "pipeline_bundle.zip").read_bytes(), tmp_path)',
        "    spec = load_spec(tmp_path).spec",
        "    expected, current = [], None",
        "    for t, rule in spec.ordered_rules():",
        "        if t.task_id != current:",
        "            current = t.task_id",
        '            expected.append(("task", t.task_id))',
        '        expected.append(("step", rule.rule_id))',
        "    recorder = _Recorder()",
        "    task.run_pipeline(recorder)",
        "    assert recorder.calls == expected",
    ]
    if queue and smoke_env:
        lines += [
            "",
            "",
            "def test_an_empty_queue_is_a_clean_run(tmp_path, monkeypatch):",
            '    moto = pytest.importorskip("moto")',
            "    import boto3",
            "",
            "    task = _task_module()",
            f'    cfg = json.loads((PIPELINE_DIR / "config_{smoke_env}.json").read_text())',
            '    region, queue_url = cfg["runtime"]["region"], cfg["poll"]["queue_url"]',
            '    for name in ("AWS_PROFILE", "AWS_SESSION_TOKEN", "AWS_ENDPOINT_URL"):',
            "        monkeypatch.delenv(name, raising=False)",
            '    monkeypatch.setenv("AWS_ACCESS_KEY_ID", "testing")',
            '    monkeypatch.setenv("AWS_SECRET_ACCESS_KEY", "testing")',
            '    monkeypatch.setenv("AWS_DEFAULT_REGION", region)',
            '    monkeypatch.setenv("MOTO_ACCOUNT_ID", queue_url.rsplit("/", 2)[1])',
            f'    monkeypatch.setenv(task.ENV_VAR, "{smoke_env}")',
            '    monkeypatch.setenv("FACTORY_WORKDIR", str(tmp_path))',
            "    with moto.mock_aws():",
            '        location = {} if region == "us-east-1" else {"LocationConstraint": region}',
            '        boto3.client("s3", region_name=region).create_bucket(',
            '            Bucket=cfg["runtime"]["staging_bucket"], CreateBucketConfiguration=location',
            "        )",
            '        sqs = boto3.client("sqs", region_name=region)',
            '        sqs.create_queue(QueueName=queue_url.rsplit("/", 1)[1])',
            "        assert task.main() == 0",
        ]
    return "\n".join(lines) + "\n"
