"""DAG generator (mwaa-strategy.md §8): one Airflow 3 DAG per pipeline, deterministic source, no top-level I/O.

Engine → operator: `lambda` → FactoryLambdaOperator (exit code mapped: 75 retried, others fail fast);
`eks_pod`/`eks_pod_spot` → FactoryPodOperator (KubernetesPodOperator, spot via node selector and toleration);
`mwaa`/`fivetran_*` → FactoryPollSensor (reschedule mode; each poke invokes the runtime Lambda with a poll budget).
`auto` engines come from the planner. dag_run_id = run_dir(run_key) (dispatcher) and conf carries ids and hashes only;
the runtime receives the run key, attempt and run id, never data.
"""

from __future__ import annotations

import json
from typing import Any

from factory_spec.spec import PipelineSpec

from ..plan.engine import plan
from . import names
from .names import Deploy

POD_SIZES = {"data": ("1", "2Gi"), "control": ("250m", "512Mi")}
RUN_KEY = "{{ (dag_run.conf or {}).get('run_key') or run_id }}"
HEADER = '''"""GENERATED by `factory build` from pipelines/{pid}/spec — do not edit (edits are refused by the hooks).

spec {spec_version} · logic_sha {logic} · bundle {bundle}
"""

from datetime import timedelta

from airflow.sdk import DAG
from factory_airflow.operators import FactoryLambdaOperator, FactoryPodOperator, FactoryPollSensor

'''


def _py(value: Any) -> str:
    """A Python literal for JSON-like data (sorted, stable)."""
    return json.dumps(value, sort_keys=True).replace("true", "True").replace("false", "False").replace("null", "None")


def _conf(spec: PipelineSpec) -> str | None:
    trig = spec.pipeline.trigger
    if trig.type == "manual":
        return "{{ (dag_run.conf or {}) | tojson }}"
    if trig.type == "schedule":
        return '{"data_interval_start": "{{ data_interval_start }}"}'
    return None


def _schedule(spec: PipelineSpec, env: str) -> str | None:
    trig = spec.pipeline.trigger
    override = spec.environments.environments[env].schedule_cron
    if trig.type == "schedule":
        return override or trig.cron
    if trig.type == "sqs" and trig.mode == "in_task":
        return override or "*/15 * * * *"
    return None


def generate_dag(spec: PipelineSpec, deploy: Deploy, logic_sha: str) -> str:
    p = spec.pipeline
    decisions = {d["task_id"]: d for d in plan(spec)["engine_decisions"]}
    sec = spec.security.security_and_access
    retry = p.reliability.retry
    conf = _conf(spec)
    runtime = {"bundle": deploy.bundle_uri, "sha256": deploy.bundle_sha256, "run_key": RUN_KEY,
               "attempt": "{{ ti.try_number }}", "run_id": "{{ run_id }}"}  # fmt: skip
    if conf:
        runtime["conf"] = conf
    tags = sorted({f"team:{spec.pipeline.metadata.team}", f"classification:{sec.data_classification}",
                   f"gxp:{sec.gxp_tier}", f"spec:{p.metadata.spec_version}"})  # fmt: skip
    out = [HEADER.format(pid=spec.pipeline_id, spec_version=p.metadata.spec_version, logic=logic_sha[:12],
                         bundle=deploy.bundle_sha256[:12])]  # fmt: skip
    out.append(f"DEFAULT_ARGS = {_py({'owner': spec.pipeline.metadata.team})}\n")
    out.append(f"RUNTIME = {_py(runtime)}\n\n")
    out.append(
        "with DAG(\n"
        f"    dag_id={spec.pipeline_id!r},\n"
        f"    schedule={_schedule(spec, deploy.env)!r},\n"
        "    start_date=None,\n"
        f"    catchup={p.orchestration.dag.catchup!r},\n"
        f"    max_active_runs={p.orchestration.dag.max_active_runs},\n"
        f"    dagrun_timeout=timedelta(seconds={p.orchestration.dag.timeout}),\n"
        f"    tags={tags!r},\n"
        "    default_args=DEFAULT_ARGS,\n"
        "    render_template_as_native_obj=False,\n"
        ") as dag:\n"
    )
    pool = p.orchestration.pool or f"team_{spec.pipeline.metadata.team}"
    team = spec.pipeline.metadata.team
    for t in p.orchestration.tasks:
        d = decisions[t.task_id]
        engine = d["choice"] if t.engine == "auto" else t.engine
        r = t.retry or retry
        args: dict[str, str] = {
            "task_id": repr(t.task_id),
            "pool": repr(pool),
            "retries": str(r.max_attempts - 1),
            "retry_delay": f"timedelta(seconds={r.base})",
            "max_retry_delay": f"timedelta(seconds={r.max})",
            "retry_exponential_backoff": "True",
            "execution_timeout": f"timedelta(seconds={t.timeout})",
            "runtime": f"{{**RUNTIME, 'task': {t.task_id!r}}}",
        }
        if engine == "lambda":
            op = "FactoryLambdaOperator"
            args["function_name"] = repr(names.lambda_function(team, spec.pipeline_id, t.task_id))
        elif engine in ("eks_pod", "eks_pod_spot"):
            op = "FactoryPodOperator"
            data = any(e.get("seconds_max", 0) > 60 for e in d["estimates"].values())
            cpu, mem = POD_SIZES["data" if data else "control"]
            args |= {"image": repr(deploy.image), "namespace": repr(names.namespace(team)),
                     "service_account_name": repr(names.service_account(spec.pipeline_id, t.task_id)),
                     "cpu": repr(cpu), "memory": repr(mem), "spot": repr(engine == "eks_pod_spot")}  # fmt: skip
        else:  # mwaa, fivetran_*: each poke invokes the runtime Lambda with a poll budget; the sensor reschedules
            op = "FactoryPollSensor"
            args |= {"function_name": repr(names.lambda_function(team, spec.pipeline_id, t.task_id)),
                     "timeout": str(t.timeout), "poke_interval": "60", "retries": "0"}  # fmt: skip
            del args["execution_timeout"]
        body = ",\n        ".join(f"{k}={v}" for k, v in args.items())
        out.append(f"    {t.task_id} = {op}(\n        {body},\n    )\n")
    out.extend(f"    {dep} >> {t.task_id}\n" for t in p.orchestration.tasks for dep in t.depends_on)
    return "".join(out)
