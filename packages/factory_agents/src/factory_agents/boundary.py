"""The LLM boundary (ADR-0022): what may be put in front of a model, and how.

Prompts are built only from typed parts: instructions, spec excerpts, schemas, the op catalog, validator output,
synthetic samples and requirement text. Requirement text is the one free-text input: secrets are redacted and it is
fenced in tags it cannot close. Samples must be marked synthetic (generated by factory_testing); there is no part
type for real data, files or credentials. Adapted from pf `llm/base.py` (fence, redact_secrets).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any, Literal

from .errors import AgentError

PartKind = Literal["instructions", "spec", "schema", "catalog", "validator", "sample", "requirement"]
TAGS: dict[str, str] = {"spec": "spec", "schema": "spec", "catalog": "catalog", "validator": "validator",
                        "sample": "sample", "requirement": "requirement"}  # fmt: skip
SECRET_PATTERNS = [
    r"-----BEGIN [A-Z ]*PRIVATE KEY-----[\s\S]*?-----END [A-Z ]*PRIVATE KEY-----",
    r"\bAKIA[0-9A-Z]{16}\b",
    r"\bASIA[0-9A-Z]{16}\b",
    r"(?i)\b(password|passwd|pwd|secret|api[_ -]?key|token|access[_ -]?key|client[_ -]?secret)\b"
    r"(\s*(is|:|=)\s*)([^\s,;]{4,})",
    r"\bgh[pousr]_[A-Za-z0-9]{30,}\b",
    r"\bxox[abposr]-[A-Za-z0-9-]{10,}\b",
    r"\bBearer\s+[A-Za-z0-9._~+/=-]{16,}",
]
MAX_PART = 200_000


def redact_secrets(text: str) -> tuple[str, int]:
    n = 0

    def repl(m: re.Match[str]) -> str:
        nonlocal n
        n += 1
        if m.lastindex and m.lastindex >= 4:
            return f"{m.group(1)}{m.group(2)}[REDACTED]"
        return "[REDACTED]"

    for pat in SECRET_PATTERNS:
        text = re.sub(pat, repl, text)
    return text, n


def fence(tag: str, text: str) -> str:
    """Wrap untrusted text in <tag>…</tag>; any tag of the boundary inside the text is neutralised."""
    names = "|".join(sorted(set(TAGS.values())))
    safe = re.sub(rf"<\s*/?\s*({names})\b[^>]*>", lambda m: f"[{m.group(1)}]", text, flags=re.IGNORECASE)
    return f"<{tag}>\n{safe}\n</{tag}>"


@dataclass(frozen=True)
class Part:
    kind: PartKind
    content: Any
    label: str = ""
    synthetic: bool = False


def build_prompt(parts: list[Part]) -> tuple[str, int]:
    """The prompt text and the number of secrets redacted from requirement text."""
    out: list[str] = []
    redacted = 0
    for p in parts:
        text = p.content if isinstance(p.content, str) else json.dumps(p.content, indent=1, sort_keys=True)
        if len(text) > MAX_PART:
            raise AgentError("prompt_part_too_large", f"prompt part '{p.label or p.kind}' is too large")
        if p.kind == "instructions":
            out.append(text)
            continue
        if p.kind == "sample" and not p.synthetic:
            raise AgentError("sample_not_synthetic", "only synthetic samples may be shown to an agent")
        if p.kind == "requirement":
            text, n = redact_secrets(text)
            redacted += n
        title = f"{p.label}:\n" if p.label else ""
        out.append(title + fence(TAGS[p.kind], text))
    return "\n\n".join(out), redacted
