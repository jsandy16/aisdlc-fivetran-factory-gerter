"""Claude Code hooks (wired by the plugin's hooks/hooks.json). Input: the hook JSON on stdin.

pre-tool   PreToolUse: deny edits to generated or person-owned files, person-only commands, and changes to the
           guard environment. Fails closed: unreadable input or an unparseable command is denied.
post-edit  PostToolUse on Write|Edit: validate the pipeline's specs right after an edit; exit 2 sends the
           errors back to Claude so it fixes them in the same turn.

These are guard rails for a cooperative agent, not a security boundary (a program the agent writes can still
open files itself). The boundaries are: deploy credentials exist only in CI; rule acceptance is bound to its
content by a digest and approved by the rule owner through CODEOWNERS review.
"""
from __future__ import annotations

import json
import posixpath
import re
import shlex
import sys
from pathlib import Path

PROTECTED = [
    (r"(^|/)pipelines/[^/]+/build/", "generated by `pf build`; change the specs instead"),
    (r"(^|/)pipelines/[^/]+/releases/", "release records are written by `pf release`"),
    (r"(^|/)pipelines/[^/]+/rules\.lock\.yaml$", "written by `pf rules compile`; acceptance is a person's action"),
    (r"(^|/)\.github/workflows/pf-[^/]+\.ya?ml$", "generated by `pf build`"),
    (r"(^|/)\.github/CODEOWNERS$", "managed by `pf build`"),
    (r"(^|/)configuration[^/]*\.json$", "never write connector secrets to files"),
]
PROTECTED_PATH = re.compile(r"(^|/)(rules\.lock\.yaml|CODEOWNERS)$|(^|/)pipelines/[^/]+/(build|releases)(/|$)|(^|/)\.github/workflows/pf-")
SECRET_ARG = re.compile(r"(FIVETRAN_API_KEY|PF_SECRET_)|(^|/)config[^/]*\.json$|(^|/)config\*")
GUARD_VARS = ("CLAUDECODE", "PF_AGENT_SESSION")
WRITERS = {"tee", "cp", "mv", "rm", "sed", "perl", "awk", "truncate", "dd", "install", "ln", "patch", "chmod", "touch"}
SEPARATORS = {";", "&&", "||", "|", "&", "|&", "(", ")", ";;"}
REVIEWER_BASH = re.compile(r"pf --json (validate|status|catalog|schema|rules list)( [a-z0-9_]+)?( --allow-unfilled)?")


def _deny(reason: str) -> int:
    print(json.dumps({"hookSpecificOutput": {"hookEventName": "PreToolUse", "permissionDecision": "deny",
                                             "permissionDecisionReason": f"pipeline-factory: {reason}"}}))
    return 0


def _norm(path: str, cwd: str) -> str:
    p = path.replace("\\", "/")
    if cwd and not p.startswith("/"):
        p = posixpath.join(cwd.replace("\\", "/"), p)
    return posixpath.normpath(p)


def _segments(cmd: str) -> list[list[str]]:
    """Tokenise like a shell: quotes removed, `# comments` dropped, split at ; && || | & and newlines.
    Redirections stay as their own tokens ('>', '>>')."""
    lex = shlex.shlex(cmd.replace("\n", " ; "), posix=True, punctuation_chars=";&|()<>")
    lex.whitespace_split = True
    segs: list[list[str]] = [[]]
    for tok in lex:
        if tok in SEPARATORS:
            segs.append([])
        else:
            segs[-1].append(tok)
    return [s for s in segs if s]


def _pf_reason(words: list[str]) -> str | None:
    words = [w for w in words if w != "--json"]
    sub = words[0] if words else ""
    if sub == "deploy" and "--dry-run" not in words:
        return "deployment runs in CI after review; use --dry-run"
    if sub == "rules" and len(words) > 1 and words[1] == "accept":
        return "accepting a compiled rule is the rule owner's decision"
    if sub == "fivetran" and "ensure-destination" in words and "--dry-run" not in words:
        return "destinations are created by the platform team"
    if sub == "hook":
        return "hooks are run by Claude Code"
    return None


def _bash_reason(cmd: str, cwd: str) -> str | None:
    try:
        segments = _segments(cmd)
    except ValueError:
        return "command could not be parsed safely"
    here = cwd
    for argv in segments:
        while argv and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*=.*", argv[0]):  # leading VAR=value
            if argv[0].split("=", 1)[0] in GUARD_VARS:
                return "the agent-session marker must not be changed"
            argv = argv[1:]
        if not argv:
            continue
        prog = posixpath.basename(argv[0])
        args = argv[1:]
        if prog.startswith("$") or "$(" in argv[0] or "`" in argv[0]:
            return "commands must name their program literally"
        if prog in ("env", "printenv") and (not args or prog == "printenv" or any(a.startswith("-u") or a == "--unset" for a in args)
                                           or any(a.split("=", 1)[0] in GUARD_VARS for a in args)):
            return "listing the environment or unsetting the agent-session marker is not allowed"
        if prog in ("unset", "export") and any(a.split("=", 1)[0] in GUARD_VARS for a in args):
            return "the agent-session marker must not be changed"
        if any(SECRET_ARG.search(a) for a in argv if " " not in a):
            return "connector configuration and secrets are only available in CI"
        if prog in ("sh", "bash", "zsh", "dash", "ksh") and "-c" in args:
            inner = args[args.index("-c") + 1] if args.index("-c") + 1 < len(args) else ""
            reason = _bash_reason(inner, here)
            if reason:
                return reason
            continue
        if prog in ("eval", "source", ".", "xargs"):
            return f"{prog} hides the command it runs"
        if prog == "cd" and args:
            here = _norm(args[0], here)
            continue
        if prog == "pf":
            reason = _pf_reason(args)
            if reason:
                return reason
            continue
        if prog.startswith("python"):
            if len(args) >= 2 and args[0] == "-m" and args[1] in ("pf", "pf.cli"):
                reason = _pf_reason(args[2:])
                if reason:
                    return reason
                continue
            code = " ".join(args)
            if re.search(r"\bpf\.|accept_rule|rules\.lock|/build/|/releases/|CODEOWNERS", code):
                return "call pf through its CLI; generated and person-owned files are written only by pf"
        if prog == "fivetran" and "deploy" in args:
            return "deployment runs in CI after review"
        paths = [_norm(a, here) for a in args if not a.startswith("-")]
        hits = [p for p in paths if PROTECTED_PATH.search(p)]
        redirect = any(t in (">", ">>") for t in argv)
        if hits and (redirect or prog in WRITERS or (prog == "git" and args and args[0] in ("apply", "checkout", "restore", "mv", "rm"))):
            return f"{hits[0]} is written only by pf (generated or person-owned)"
        if redirect:
            i = max(i for i, t in enumerate(argv) if t in (">", ">>"))
            if i + 1 < len(argv) and PROTECTED_PATH.search(_norm(argv[i + 1], here)):
                return f"{argv[i + 1]} is written only by pf (generated or person-owned)"
        if prog == "git" and args and args[0] == "apply":
            return "patches can rewrite generated and person-owned files; edit the specs instead"
    return None


def pre_tool(data: dict) -> int:
    tool = data.get("tool_name", "")
    ti = data.get("tool_input") or {}
    cwd = str(data.get("cwd") or "")
    if str(data.get("agent_type", "")).endswith("pipeline-spec-reviewer"):  # the reviewer is read-only
        if tool in ("Read", "Grep", "Glob") and not re.search(r"configuration[^/]*\.json|\.env", str(ti.get("file_path") or ti.get("path") or "")):
            return 0
        if tool == "Bash" and REVIEWER_BASH.fullmatch(str(ti.get("command", "")).strip()):
            return 0
        return _deny("the spec reviewer only reads files and runs read-only pf commands")
    if tool in ("Write", "Edit", "MultiEdit", "NotebookEdit"):
        path = _norm(str(ti.get("file_path") or ti.get("notebook_path") or ""), cwd)
        for rx, why in PROTECTED:
            if re.search(rx, path):
                return _deny(f"{path} is protected: {why}")
    if tool in ("Bash", "PowerShell"):
        reason = _bash_reason(str(ti.get("command", "")), cwd)
        if reason:
            return _deny(reason)
    if tool == "Read":
        path = _norm(str(ti.get("file_path") or ""), cwd)
        if re.search(r"(^|/)configuration[^/]*\.json$|(^|/)\.env", path):
            return _deny("connector configuration holds secrets")
    return 0


def post_edit(data: dict) -> int:
    ti = data.get("tool_input") or {}
    path = Path(_norm(str(ti.get("file_path", "")), str(data.get("cwd") or "")))
    m = re.search(r"(^|/)pipelines/([^/]+)/(pipeline|source|destination|sttm|quality|policy)\.yaml$", path.as_posix())
    if not m:
        return 0
    from .bundle import load_bundle

    b = load_bundle(path.parent)
    errs = [i for i in b.issues if i.severity == "error" and i.code != "required"]
    if not errs:
        return 0
    lines = [f"pf validate found {len(errs)} problem(s) after this edit — fix them now:"]
    lines += [f"- {i.file}:{i.loc}: {i.msg}" for i in errs[:15]]
    print("\n".join(lines), file=sys.stderr)
    return 2


def run_hook(event: str) -> int:
    try:
        data = json.load(sys.stdin)
        if not isinstance(data, dict):
            raise ValueError("not an object")
    except (json.JSONDecodeError, ValueError):
        print("pipeline-factory: unreadable hook input", file=sys.stderr)
        return 2 if event == "pre-tool" else 0  # fail closed before a tool runs
    return pre_tool(data) if event == "pre-tool" else post_edit(data)
