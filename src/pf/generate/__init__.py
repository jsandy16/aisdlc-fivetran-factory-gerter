"""Deterministic generators: locked spec in, files out. Same input -> byte-identical output.

`pf build` writes everything under pipelines/<name>/build/ plus the pipeline's CI workflow, and a
BUILD-MANIFEST.json with the sha256 of every file. `pf build --check` regenerates in memory and fails on
any difference (hand edits or stale builds), which CI runs on every pull request.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

from .. import VERSION
from ..bundle import Bundle
from ..lock import build_lock
from . import cicd, codeowners, connector, docs, quality, terraform

MANIFEST = "BUILD-MANIFEST.json"


def header(b: Bundle, lock: dict, comment: str = "#") -> str:
    return (f"{comment} Generated by pipeline-factory {VERSION} from pipelines/{b.name} (spec sha256 {lock['spec_sha256'][:16]}).\n"
            f"{comment} Do not edit: change the specs and run `pf build {b.name}`.\n")


def render_all(b: Bundle, root: Path) -> dict[str, bytes]:
    """Return {path relative to repo root: content}. Pure function of the bundle."""
    lock = build_lock(b)
    base = f"pipelines/{b.name}/build"
    files: dict[str, str | bytes] = {}
    files[f"{base}/spec.lock.json"] = json.dumps(lock, indent=2, sort_keys=True) + "\n"
    for rel, content in connector.render(b, lock, header(b, lock)).items():
        files[f"{base}/connector/{rel}"] = content
    for rel, content in quality.render(b, lock, header(b, lock, "--")).items():
        files[f"{base}/quality/{rel}"] = content
    for rel, content in terraform.render(b, lock, header(b, lock)).items():
        files[f"{base}/terraform/{rel}"] = content
    for rel, content in docs.render(b, lock, header(b, lock)).items():
        files[f"{base}/{rel}"] = content
    files[f".github/workflows/pf-{b.name.replace('_', '-')}.yml"] = cicd.render_workflow(b, lock, header(b, lock))
    out: dict[str, bytes] = {}
    for k, v in sorted(files.items()):
        data = v.encode("utf-8") if isinstance(v, str) else v
        out[k] = data.replace(b"\r\n", b"\n") if not k.endswith((".zip",)) else data
    manifest = {
        "pipeline": b.name, "version": lock["version"], "framework_version": VERSION, "runtime_version": lock["runtime_version"],
        "spec_sha256": lock["spec_sha256"], "rules_lock_sha256": lock["rules_lock_sha256"],
        "files": {k: hashlib.sha256(v).hexdigest() for k, v in out.items()},
    }
    out[f"{base}/{MANIFEST}"] = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return out


FOUNDATION_HEADER = ("# Generated by pipeline-factory from every pipeline in this repository (account-level objects).\n"
                     "# Do not edit: change the pipelines' policy/destination specs and run `pf build`.\n")


def render_foundation(root: Path) -> dict[str, bytes]:
    return terraform.render_foundation(root, FOUNDATION_HEADER)


def write_foundation(root: Path, files: dict[str, bytes]) -> None:
    import shutil

    shutil.rmtree(root / "foundation", ignore_errors=True)  # aggregated: rewritten whole
    for rel, data in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)


def write(root: Path, files: dict[str, bytes], name: str) -> list[str]:
    base = root / "pipelines" / name / "build"
    # remove files a previous build produced that this build no longer does
    old = base / MANIFEST
    if old.exists():
        for rel in json.loads(old.read_text())["files"]:
            p = root / rel
            if rel not in files and p.exists():
                p.unlink()
    for rel, data in files.items():
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data)
    codeowners.update(root, name)
    return sorted(files)


def check(root: Path, files: dict[str, bytes]) -> list[str]:
    diffs = []
    for rel, data in files.items():
        p = root / rel
        if not p.exists():
            diffs.append(f"missing: {rel}")
        elif p.read_bytes() != data:
            diffs.append(f"differs: {rel}")
    base = None
    for rel in files:
        if rel.endswith(MANIFEST):
            base = Path(rel).parent
    if base is not None and (root / base).exists():
        for p in (root / base).rglob("*"):
            rel = p.relative_to(root / base).parts
            if (not p.is_file() or "__pycache__" in p.parts or p.name.startswith(".") or p.name == "TEST-REPORT.json"
                    or rel[:2] == ("connector", "files") or rel == ("connector", "configuration.json")):
                continue  # local test output, never part of the build
            if p.relative_to(root).as_posix() not in files:
                diffs.append(f"unexpected: {p.relative_to(root).as_posix()}")
    return diffs

