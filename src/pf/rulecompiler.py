"""English rules -> CEL, at build time only (`pf rules compile`), never at runtime.

For each English rule:
  1. the compiling-english-rules skill drafts a CEL expression, ambiguities and edge cases (LLM, structured);
  2. deterministic checks: the expression parses, uses only known names, and gives the expected result on every
     owner-labelled example and every generated case (evaluated by the same engine the runtime uses);
  3. the explaining-compiled-rules skill, which never sees the English, explains the expression back (LLM);
  4. the entry is frozen in rules.lock.yaml with hashes of text, examples, skill and prompt;
  5. a person accepts it (`pf rules accept`). Builds use only accepted entries whose text hash still matches.
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

from . import yamlio
from .envelope import Issue, PfError

LOCK_FILE = "rules.lock.yaml"


class Case(BaseModel):
    model_config = ConfigDict(extra="forbid")
    input: dict[str, Any]
    expected: Literal["pass", "fail"]
    actual: Literal["pass", "fail"]
    source: Literal["owner", "generated"]
    why: str = ""


class RuleEntry(BaseModel):
    model_config = ConfigDict(extra="forbid")
    scope: Literal["package", "attribute", "row"]
    location: str
    text: str
    text_sha256: str
    expression: str
    referenced: list[str]
    back_translation: str
    passes_when: list[str] = Field(default_factory=list)
    fails_when: list[str] = Field(default_factory=list)
    ambiguities: list[str] = Field(default_factory=list)
    cases: list[Case]
    verification: Literal["passed", "failed"]
    verification_issues: list[str] = Field(default_factory=list)
    compiled_by: dict[str, Any]
    status: Literal["compiled", "accepted"] = "compiled"
    accepted_by: str | None = None
    accepted_identity: str | None = None  # git user.email or GITHUB_ACTOR of whoever ran accept
    accepted_at: str | None = None
    acceptance_sha256: str | None = None  # binds the acceptance to text, expression, references and cases

    def acceptance_digest(self) -> str:
        payload = {"scope": self.scope, "text_sha256": self.text_sha256, "expression": self.expression,
                   "referenced": sorted(self.referenced),
                   "cases": sorted((json.dumps(c.input, sort_keys=True, default=str), c.expected, c.source) for c in self.cases)}
        return hashlib.sha256(json.dumps(payload, sort_keys=True).encode()).hexdigest()


class RulesLock(BaseModel):
    model_config = ConfigDict(extra="forbid")
    lock_version: Literal[1] = 1
    rules: dict[str, RuleEntry] = Field(default_factory=dict)

    def sha256(self) -> str:
        return hashlib.sha256(json.dumps(self.model_dump(mode="json"), sort_keys=True).encode()).hexdigest()


@dataclass
class EnglishRef:
    rule_id: str
    scope: str
    file: str
    loc: str
    text: str
    examples: list[dict]
    entity: str = ""
    attribute: str = ""
    columns: dict[str, str] | None = None  # name -> type, for row/attribute rules


def text_sha(text: str, examples: list[dict]) -> str:
    return hashlib.sha256(json.dumps([text.strip(), examples], sort_keys=True, default=str).encode()).hexdigest()


def english_rules(b) -> list[EnglishRef]:
    refs: list[EnglishRef] = []
    if b.source and b.source.source.type in ("sftp", "ftp"):
        for j, c in enumerate(b.source.source.package.checks):
            if c.kind == "english":
                refs.append(EnglishRef(c.id, "package", "source.yaml", f"source.package.checks.{j}", c.text,
                                       [x.model_dump(mode="json") for x in c.examples]))
    for i, e in enumerate(b.sttm.entities if b.sttm else []):
        cols = {a.name: a.type for a in e.attributes}
        for k, a in enumerate(e.attributes):
            for j, c in enumerate(a.checks):
                if c.kind == "english":
                    refs.append(EnglishRef(c.id, "attribute", "sttm.yaml", f"entities.{i}.attributes.{k}.checks.{j}", c.text,
                                           [x.model_dump(mode="json") for x in c.examples], e.name, a.name, cols))
        for j, c in enumerate(e.row_checks):
            if c.kind == "english":
                refs.append(EnglishRef(c.id, "row", "sttm.yaml", f"entities.{i}.row_checks.{j}", c.text,
                                       [x.model_dump(mode="json") for x in c.examples], e.name, "", cols))
    return refs


def load_rules_lock(path: Path) -> RulesLock | None:
    f = path / LOCK_FILE
    if not f.exists():
        return None
    return RulesLock.model_validate(yamlio.to_plain(yamlio.load(f)) or {})


def save_rules_lock(path: Path, rl: RulesLock) -> None:
    header = ("# rules.lock.yaml — compiled English rules. Generated by `pf rules compile`; accepted by people with\n"
              "# `pf rules accept`. Review every expression, case and back-translation before accepting.\n")
    body = yamlio.dumps(json.loads(json.dumps(rl.model_dump(mode="json"))))
    (path / LOCK_FILE).write_text(header + body, encoding="utf-8", newline="\n")


# ---------------------------------------------------------------------------- deterministic verification
PACKAGE_FACTS = {"name": "STRING", "path": "STRING", "folder": "STRING", "size": "LONG", "sha256": "STRING", "members": "LIST", "groups": "MAP"}


def evaluate(ref: EnglishRef, expression: str, values: dict[str, Any]) -> bool:
    from pf_runtime import cel

    if ref.scope == "package":
        act = {"package": {**{k: None for k in PACKAGE_FACTS}, **values}}
    else:
        row = {**{c: None for c in (ref.columns or {})}, **values}
        act = {"row": row, "value": row.get(ref.attribute) if ref.scope == "attribute" else None}
    ok, _ = cel.evaluate(expression, act)
    return ok


def verify(ref: EnglishRef, expression: str, referenced: list[str], cases: list[Case]) -> list[str]:
    import celpy

    problems: list[str] = []
    try:
        celpy.Environment().compile(expression)
    except Exception as exc:
        return [f"expression does not parse: {str(exc).splitlines()[0]}"]
    if ref.scope == "package":
        allowed = {f"package.{k}" for k in PACKAGE_FACTS}
        used = {f"package.{m}" for m in re.findall(r"\bpackage\.([A-Za-z_]\w*)", expression)}
        if re.search(r"\b(row|value)\b", expression):
            problems.append("package rules may only use package.<fact>")
    else:
        allowed = {f"row.{c}" for c in (ref.columns or {})} | {"value"}
        used = {f"row.{m}" for m in re.findall(r"\brow\.([A-Za-z_]\w*)", expression)}
        if re.search(r"\bvalue\b", expression):
            used.add("value")
        if ref.scope == "row" and "value" in used:
            problems.append("row rules may not use `value`; use row.<column>")
    unknown = sorted(used - allowed)
    if unknown:
        problems.append(f"expression uses unknown names {unknown}")
    if re.search(r"\b(row|package)\s*\[", expression):
        problems.append("use row.<column> / package.<fact>, not index syntax (names are checked)")
    for c in cases:
        if c.actual != c.expected:
            problems.append(f"{c.source} case {json.dumps(c.input, sort_keys=True)} expected {c.expected} but the expression gives {c.actual}")
    if len([c for c in cases if c.source == "generated"]) < 6:
        problems.append("fewer than 6 generated boundary cases")
    if not problems:
        for m in surviving_mutants(ref, expression, cases):
            problems.append(f"the cases cannot tell the expression from `{m}`: add an example at that boundary")
    return problems


_OPS = [("<=", "<"), (">=", ">"), ("==", "!="), ("!=", "=="), ("<", "<="), (">", ">=")]


def surviving_mutants(ref: "EnglishRef", expression: str, cases: list[Case]) -> list[str]:
    """Deterministic mutation testing: flip one comparison operator at a time (and drop each `x == null ||`
    allowance). A mutant that every case still classifies the same way means the cases do not pin that boundary,
    so a wrong expression would have verified just as well."""
    masked = re.sub(r'"(?:[^"\\]|\\.)*"|\'(?:[^\'\\]|\\.)*\'', lambda m: "\0" * len(m.group(0)), expression)
    mutants: list[str] = []
    for m in re.finditer(r"<=|>=|==|!=|<|>", masked):
        op = m.group(0)
        for a, b in _OPS:
            if op == a:
                mutants.append(expression[:m.start()] + b + expression[m.end():])
                break
    nullables: dict[str, str] = {}
    for m in re.finditer(r"([A-Za-z_][\w.]*)\s*==\s*null\s*\|\|\s*", masked):
        mu = expression[:m.start()] + expression[m.end():]
        mutants.append(mu)
        nullables[mu] = re.sub(r"^(row|package)\.", "", m.group(1))
    survivors = []
    for mu in mutants:
        try:
            outcomes = ["pass" if evaluate(ref, mu, c.input) else "fail" for c in cases]
        except Exception:  # noqa: BLE001 - a mutant that does not even compile is killed
            continue
        if not all(o == c.expected for o, c in zip(outcomes, cases)):
            continue
        if mu in nullables:  # dropping a null allowance can be equivalent (e.g. null != "X" is already true)
            probes = [{**c.input, nullables[mu]: None} for c in cases] or [{nullables[mu]: None}]
            try:
                if all(evaluate(ref, mu, x) == evaluate(ref, expression, x) for x in probes):
                    continue  # equivalent mutant: nothing an example could distinguish
            except Exception:  # noqa: BLE001
                pass
        survivors.append(mu)
    return survivors


# ---------------------------------------------------------------------------- compile / accept
from .llm.base import fence  # noqa: E402


def _prompt_compile(ref: EnglishRef) -> str:
    if ref.scope == "package":
        names = "\n".join(f"- package.{k} ({t})" for k, t in PACKAGE_FACTS.items())
        target = "the delivery (package) as a whole"
    else:
        names = "\n".join(f"- row.{c} ({t})" for c, t in (ref.columns or {}).items())
        names += "\n- value (the attribute being checked)" if ref.scope == "attribute" else ""
        target = f"attribute `{ref.attribute}` of entity `{ref.entity}`" if ref.scope == "attribute" else f"each row of entity `{ref.entity}`"
    return (
        f"Rule id: {ref.rule_id}\nScope: {ref.scope} — applies to {target}\n\n"
        f"Available names (dates and timestamps are ISO-8601 strings; decimals are numbers; missing values are null):\n{names}\n\n"
        f"{fence('rule_text', ref.text.strip())}\n"
    )


def _prompt_explain(ref: EnglishRef, expression: str) -> str:
    cols = ", ".join(f"{c} ({t})" for c, t in (ref.columns or {}).items()) if ref.scope != "package" else ", ".join(PACKAGE_FACTS)
    return f"Scope: {ref.scope}\nNames available: {cols}\n\n<expression>\n{expression}\n</expression>\n"


def compile_rules(b, only: list[str] | None = None, log_dir: Path | None = None) -> tuple[RulesLock, list[Issue]]:
    from .llm import run_structured
    from .llm.schemas import CompiledRule, Explanation

    rl = load_rules_lock(b.path) or RulesLock()
    issues: list[Issue] = []
    refs = english_rules(b)
    wanted = {r.rule_id for r in refs} if not only else set(only)
    for ref in refs:
        if ref.rule_id not in wanted:
            continue
        tsha = text_sha(ref.text, ref.examples)
        existing = rl.rules.get(ref.rule_id)
        if existing and existing.text_sha256 == tsha and not only:
            continue  # unchanged: keep the frozen (possibly accepted) entry
        compiled, meta1 = run_structured("compile_rule", "compiling-english-rules", _prompt_compile(ref), CompiledRule, log_dir=log_dir)
        cases: list[Case] = []
        for ex in ref.examples:
            actual = "pass" if evaluate(ref, compiled.expression, ex["input"]) else "fail"
            cases.append(Case(input=ex["input"], expected=ex["expected"], actual=actual, source="owner"))
        for gc in compiled.cases:
            try:
                values = {re.sub(r"^(row|package)\.", "", v.name): json.loads(v.value_json) for v in gc.values}
            except json.JSONDecodeError:
                issues.append(Issue(file=LOCK_FILE, loc=ref.rule_id, msg="a generated case had invalid JSON; skipped", severity="warning"))
                continue
            actual = "pass" if evaluate(ref, compiled.expression, values) else "fail"
            cases.append(Case(input=values, expected=gc.expected, actual=actual, source="generated", why=gc.why))
        problems = verify(ref, compiled.expression, compiled.referenced, cases)
        explanation, meta2 = run_structured("explain_rule", "explaining-compiled-rules", _prompt_explain(ref, compiled.expression), Explanation, log_dir=log_dir)
        entry = RuleEntry(
            scope=ref.scope, location=f"{ref.file}:{ref.loc}", text=ref.text.strip(), text_sha256=tsha,
            expression=compiled.expression, referenced=sorted(set(compiled.referenced)),
            back_translation=explanation.explanation, passes_when=explanation.passes_when, fails_when=explanation.fails_when,
            ambiguities=compiled.ambiguities, cases=cases, verification="failed" if problems else "passed", verification_issues=problems,
            compiled_by={"compile": meta1.model_dump(exclude={"duration_s", "cost_usd", "turns", "provider"}),
                         "explain": meta2.model_dump(exclude={"duration_s", "cost_usd", "turns", "provider"})},
        )
        rl.rules[ref.rule_id] = entry
        if problems:
            issues.append(Issue(file=LOCK_FILE, loc=ref.rule_id, code="verification_failed", msg="; ".join(problems)))
        if compiled.ambiguities:
            issues.append(Issue(file=LOCK_FILE, loc=ref.rule_id, code="ambiguous", severity="warning",
                                msg="owner must clarify: " + " | ".join(compiled.ambiguities)))
    stale = set(rl.rules) - {r.rule_id for r in refs}
    for rid in stale:
        del rl.rules[rid]  # rule removed from the specs
    save_rules_lock(b.path, rl)
    return rl, issues


def _identity(path) -> str | None:
    """Who ran the command: CI actor, else git user.email. Recorded next to the free-text --by handle."""
    import os
    import subprocess

    if os.environ.get("GITHUB_ACTOR"):
        return "github:" + os.environ["GITHUB_ACTOR"]
    try:
        out = subprocess.run(["git", "-C", str(path), "config", "user.email"], capture_output=True, text=True, timeout=10).stdout.strip()
        return out or None
    except (OSError, subprocess.SubprocessError):
        return None


def reverify(ref: "EnglishRef", entry: RuleEntry) -> list[str]:
    """Re-run every stored case with the runtime CEL engine and re-check names and mutants: what was accepted must
    still be true of the expression that will run."""
    cases = [Case(input=c.input, expected=c.expected, actual="pass" if evaluate(ref, entry.expression, c.input) else "fail",
                  source=c.source, why=c.why) for c in entry.cases]
    return verify(ref, entry.expression, entry.referenced, cases)


def accept_rule(b, rule_id: str, by: str) -> RuleEntry:
    if not re.fullmatch(r"@[\w.-]+(/[\w.-]+)?", by):
        raise PfError("--by must be a GitHub handle like @jane", "invalid")
    rl = load_rules_lock(b.path)
    if rl is None or rule_id not in rl.rules:
        raise PfError(f"rule '{rule_id}' is not compiled", "not_compiled")
    ref = next((r for r in english_rules(b) if r.rule_id == rule_id), None)
    entry = rl.rules[rule_id]
    if ref is None or entry.text_sha256 != text_sha(ref.text, ref.examples):
        raise PfError(f"rule '{rule_id}' changed since it was compiled; compile it again", "stale")
    if entry.verification != "passed":
        raise PfError(f"rule '{rule_id}' failed verification: {'; '.join(entry.verification_issues)}", "verification_failed")
    if entry.ambiguities:
        raise PfError(f"rule '{rule_id}' has open questions; reword the rule text to answer them, then compile again", "ambiguous")
    owner = [c for c in entry.cases if c.source == "owner"]
    if len(owner) < 3 or not {c.expected for c in owner} >= {"pass", "fail"}:
        raise PfError(f"rule '{rule_id}' needs at least 3 owner-labelled examples, including a pass and a fail", "no_examples")
    problems = reverify(ref, entry)
    if problems:
        raise PfError(f"rule '{rule_id}' does not re-verify: {'; '.join(problems)}", "verification_failed")
    entry.status = "accepted"
    entry.accepted_by = by
    entry.accepted_identity = _identity(b.path)
    entry.accepted_at = dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()
    entry.acceptance_sha256 = entry.acceptance_digest()
    save_rules_lock(b.path, rl)
    return entry
